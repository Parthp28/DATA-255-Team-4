"""Build data_v1 from the cached raw OHLCV files (G1; owner Farzaan).

    python scripts/build_dataset.py --config configs/data.yaml [--data-dir data] [--offline]

Steps: download missing tickers into data/raw (sha256 manifest) -> verify cache ->
clean -> global calendar -> rolling windows -> split + purge/embargo + stride ->
labels from train-only tertiles -> leakage checks (abort on failure) -> write

    data/data_v1/windows.parquet     window registry (Execution Plan 10.1)
    data/data_v1/ohlcv.npy           (N, 30, 5) float32 O,H,L,C,V input windows
    data/data_v1/thresholds.json     train-only tertile thresholds of z
    data/data_v1/split_report.md     counts, boundaries, purge derivation, label balance
    data/data_v1/build_manifest.json config/raw/output hashes, git commit
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.data import download as dl  # noqa: E402
from src.data import splits as sp  # noqa: E402
from src.data.labels import CLASS_NAMES  # noqa: E402
from src.data.windows import build_windows  # noqa: E402


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def git_state() -> dict:
    try:
        commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
        dirty = bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=ROOT, text=True).strip())
        return {"git_commit": commit, "git_dirty": dirty}
    except Exception:
        return {"git_commit": None, "git_dirty": None}


def ticker_list(cfg: dict) -> tuple[list[str], dict[str, str]]:
    tickers, kind = [], {}
    for asset_type in ("stock", "etf"):
        for t in cfg["tickers"].get(asset_type, []):
            tickers.append(t)
            kind[t] = asset_type
    return tickers, kind


def split_report(res, cfg: dict) -> str:
    w, plan, cal = res.windows, res.plan, res.calendar
    L, H, stride = plan.input_len, plan.horizon, plan.stride
    lines = [f"# Split report ({cfg['data_version']})", ""]
    lines += ["Generated by `scripts/build_dataset.py` from the cached raw files; do not edit by hand.", ""]
    lines += ["## Calendar and boundaries", "",
              f"- Global trading calendar: {plan.n_days} days, {cal[0]} to {cal[-1]}",
              f"- Window: L = {L} input days, H = {H} label days, stride = {stride} (applied after split assignment)",
              f"- Validation boundary B_val = {cal[plan.b_val]}; test boundary B_test = {cal[plan.b_test]}",
              f"- Strict purge: train anchors d <= B-{H + 1}, evaluation anchors d >= B+{L - 1}; "
              f"{L + H - 1} daily anchors purged per boundary, "
              f"{sp.expected_purged_per_boundary(L, H, stride)} per ticker per boundary after striding", ""]
    lines += ["| Segment | First anchor | Last anchor |", "|---|---|---|"]
    for name, lo, hi in plan.segments:
        lines.append(f"| {name} | {cal[lo]} | {cal[hi]} |")
    lines += ["", "## Windows per split", "", "| Split | Windows | Tickers | First anchor | Last anchor |",
              "|---|---|---|---|---|"]
    for s in (*sp.SPLITS, sp.PURGED):
        g = w[w["split"] == s]
        if len(g):
            lines.append(f"| {s} | {len(g)} | {g['ticker'].nunique()} | {g['anchor_date'].min()} | "
                         f"{g['anchor_date'].max()} |")
    lines += ["", f"Total windows: {len(w)} (non-purged: {int(w['split'].isin(sp.SPLITS).sum())})", ""]
    t1, t2 = res.thresholds
    lines += ["## Labels", "",
              f"z = r / (sigma_30 * sqrt({H})); thresholds fit on train only: t1 = {t1:.6f}, t2 = {t2:.6f}", "",
              "| Split | " + " | ".join(CLASS_NAMES) + " |", "|---|---|---|---|"]
    for s in sp.SPLITS:
        g = w[w["split"] == s]
        if len(g):
            frac = g["label"].value_counts(normalize=True).reindex([0, 1, 2], fill_value=0.0)
            lines.append(f"| {s} | " + " | ".join(f"{x:.3f}" for x in frac) + " |")
    lines += ["", "## Per-ticker counts", "", "| Ticker | Type | train | val | test | purged | missing days |",
              "|---|---|---|---|---|---|---|"]
    counts = w.groupby(["ticker", "split"]).size().unstack(fill_value=0)
    for t in counts.index:
        kind = w.loc[w["ticker"] == t, "asset_type"].iloc[0]
        row = counts.loc[t]
        miss = res.report["gaps"][t]["calendar_days_missing"]
        lines.append(f"| {t} | {kind} | " + " | ".join(str(int(row.get(s, 0))) for s in
                                                         (*sp.SPLITS, sp.PURGED)) + f" | {miss} |")
    cl = res.report["cleaning"]
    lines += ["", "## Cleaning", "",
              f"- Invalid rows dropped (NaN / non-positive price / negative volume): "
              f"{sum(v['invalid_rows_dropped'] for v in cl.values())}",
              f"- Duplicate dates dropped: {sum(v['duplicate_dates'] for v in cl.values())}",
              f"- Rows with High/Low repaired to bracket Open/Close: {sum(v['hl_repaired'] for v in cl.values())}",
              f"- Windows with zero input volatility (z set to 0): {res.report['flat_sigma_windows']}",
              f"- Anchors lost to ticker gaps: {sum(v['anchors_lost_to_gaps'] for v in res.report['gaps'].values())}",
              ""]
    lines += ["## Leakage checks run at build time", "",
              "T-L1 (per-ticker and global span separation), T-L2 (anchor ordering), "
              "T-L3 (disjoint window_id sets): passed.", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/data.yaml")
    ap.add_argument("--data-dir", default=os.path.join(ROOT, "data"))
    ap.add_argument("--offline", action="store_true", help="never download; require a complete cache")
    ap.add_argument("--report-copy", default=None, help="also write split_report.md here")
    args = ap.parse_args()

    with open(args.config, "rb") as fh:
        cfg_bytes = fh.read()
    cfg = yaml.safe_load(cfg_bytes)
    version = cfg["data_version"]
    tickers, kind = ticker_list(cfg)
    raw_dir = os.path.join(args.data_dir, "raw")
    out_dir = os.path.join(args.data_dir, version)

    if not args.offline:
        dl.download_all(tickers, raw_dir, cfg["source"]["start"], cfg["source"]["end"])
    dl.verify_cache(tickers, raw_dir)
    raw = {t: dl.load_raw(raw_dir, t) for t in tickers}

    res = build_windows(raw, kind, cfg)
    sp.check_leakage(res.windows)                       # abort before writing anything

    os.makedirs(out_dir, exist_ok=True)
    wpath = os.path.join(out_dir, "windows.parquet")
    opath = os.path.join(out_dir, "ohlcv.npy")
    res.windows.to_parquet(wpath, index=False)
    np.save(opath, res.ohlcv)
    with open(os.path.join(out_dir, "thresholds.json"), "w") as fh:
        json.dump({"t1": res.thresholds[0], "t2": res.thresholds[1], "fit_on": "train",
                   "n_train": int((res.windows["split"] == "train").sum())}, fh, indent=2)
    report = split_report(res, cfg)
    with open(os.path.join(out_dir, "split_report.md"), "w") as fh:
        fh.write(report)
    if args.report_copy:
        with open(args.report_copy, "w") as fh:
            fh.write(report)

    with open(os.path.join(raw_dir, dl.MANIFEST), "rb") as fh:
        raw_manifest_sha = sha256_bytes(fh.read())
    manifest = {
        "data_version": version,
        "config_path": os.path.relpath(os.path.abspath(args.config), ROOT),
        "config_sha256": sha256_bytes(cfg_bytes),
        "raw_manifest_sha256": raw_manifest_sha,
        "windows_parquet_sha256": dl.sha256_file(wpath),
        "ohlcv_npy_sha256": dl.sha256_file(opath),
        "n_windows": int(len(res.windows)),
        "ohlcv_shape": list(res.ohlcv.shape),
        "split_counts": {k: int(v) for k, v in res.windows["split"].value_counts().items()},
        "thresholds": list(res.thresholds),
        "boundaries": res.report["calendar"],
        **git_state(),
    }
    with open(os.path.join(out_dir, "build_manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=2)
    print(json.dumps({k: manifest[k] for k in ("n_windows", "split_counts", "thresholds")}, indent=2))
    print(f"data_v1 written to {out_dir}")


if __name__ == "__main__":
    main()

def table1(w, seeds, comp):
    exps = present(EXP_ORDER, set(seeds["experiment_id"]))
    a8 = comp[(comp["comparison_id"] == "A8") & (comp["metric"] == "macro_f1")].set_index("exp_b")
    best = a8["exp_a"].iloc[0] if len(a8) else None
    rows = []
    for e in exps:
        cells = [e.replace("B0-", "B0 ")]
        for m in ("macro_f1", "macro_auroc", "FR_seen", "FR_held", "any_flip"):
            cells.append(pm(*seeds_value(seeds, e, m)))
        if e in a8.index:
            r = a8.loc[e]
            cells.append(f"{fmt(r['delta_mean'])} [{fmt(r['ci_low'])}, {fmt(r['ci_high'])}]")
        else:
            cells.append("--")
        rows.append(cells)
    note = (f"Test split, mean $\\pm$ SD over seeds. FR: flip rate against R0 (seen = R1, R2, R4; held-out = R3, R5, "
            f"R6). $\\Delta$F1: Macro F1 minus the best B0 ({best or 'n/a'}) with a 95\\% moving-block bootstrap "
            f"interval over test anchor dates. -- = not applicable.")
    w.table("table1_main.tex", ["seeds.csv", "comparisons.csv"], "Predictive performance and rendering robustness.",
            "tab:main", "lcccccc", ["Exp.", "Macro F1", "AUROC", "FR seen", "FR held-out", "Any flip",
                                    "$\\Delta$F1 vs best B0 [95\\% CI]"], rows, wide=True, note=note)



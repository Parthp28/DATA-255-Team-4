    order = ["R1", "R2", "R4", "R3", "R5", "R6"]
    x = np.arange(len(order))
    for ax, (arch, exps) in zip(axes, ARCH.items()):
        style_axes(ax)
        width = 0.26
        for k, e in enumerate(exps):
            d = per_render[(per_render["experiment_id"] == e) & per_render["render_id"].isin(order)]
            if d.empty:
                continue
            g = d.groupby("render_id")["FR"]
            m, s = g.mean().reindex(order), g.std(ddof=1).reindex(order).fillna(0)
            ax.bar(x + (k - 1) * width, m, width, color=SERIES[REGIME[e]], edgecolor="white", linewidth=1.0,
                   label=REGIME_LEGEND[REGIME[e]], zorder=2)
            ax.errorbar(x + (k - 1) * width, m, yerr=s, fmt="none", ecolor=INK2, elinewidth=0.8, capsize=0, zorder=3)
        ax.axvspan(2.5, 5.5, color=GRID, alpha=0.35, linewidth=0, zorder=0)
        ax.set_xticks(x, [f"{r}\n{SHORT[r]}" for r in order], fontsize=7)
        ax.set_title(arch, fontsize=9, color=INK, loc="left")
        ax.text(4.0, ax.get_ylim()[1] * 0.98, "held-out", ha="center", va="top", fontsize=7, color=MUTED)
    axes[0].set_ylabel("Flip rate vs R0 (mean $\\pm$ SD)", fontsize=8, color=INK2)

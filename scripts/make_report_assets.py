def generate(eval_dir, out, masking_dir=None, attribution_dir=None, freeze=None, data_root=None,
             allow_synthetic=False):
    eval_dir, out = Path(eval_dir), Path(out)
    synthetic = (eval_dir / "SYNTHETIC_NOT_RESULTS.txt").exists()
    if synthetic and not allow_synthetic:
        raise AssetRefused(f"{eval_dir} holds synthetic outputs; report assets refused (use --allow-synthetic "
                           f"to preview outside report/)")
    if synthetic and (ROOT / "report") in [out.resolve(), *out.resolve().parents]:
        raise AssetRefused("synthetic previews may not be written under report/")
    names = ("metrics_long.csv", "per_render.csv", "seeds.csv", "comparisons.csv")
    missing = [n for n in names if not (eval_dir / n).exists()]
    if missing:
        raise AssetRefused(f"{eval_dir} lacks {missing}; run scripts/evaluate.py first")
    sources = {n: sha(eval_dir / n) for n in names}
    ml, pr, sd, cp = (pd.read_csv(eval_dir / n) for n in names)
    summary = None
    if masking_dir:
        summary, msrc = masking_frames(masking_dir)
        sources.update(msrc)
    w = Writer(out, sources, synthetic)
    table1(w, sd, cp)
    table2(w, pr)
    table4(w, sd)
    table5(w, cp)
    table7(w, sd)
    fig3(w, pr)
    fig4(w, ml)
    if summary is not None and len(summary):
        table3(w, summary)
        fig7(w, summary)
    if attribution_dir:
        files = sorted(Path(attribution_dir).glob("*.parquet"))
        if files:
            sources.update({f"attribution/{p.name}": sha(p) for p in files})
            fig6(w, pd.concat([pd.read_parquet(p) for p in files], ignore_index=True))
        if freeze:
            link = attribution_link(attribution_dir, freeze, sources)
            if link is not None and len(link):
                table3b(w, link)
    if freeze:
        preds = frozen_test_predictions(freeze, sources)
        fig5(w, preds)
        fig8(w, preds)
    if data_root:
        fig1(w, data_root)
    manifest = {"synthetic": synthetic, "sources": sources, "written": sorted(w.written)}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return manifest


def attribution_link(attribution_dir, freeze, sources):
    """Attribution-to-flip AUROC from attribution files and the frozen, hash-checked test predictions."""
    sys.path.insert(0, str(ROOT / "scripts"))
    import evaluate as ev
    from src.interpretability.link import attribution_flip_auroc
    files = sorted(Path(attribution_dir).glob("*.parquet"))
    if not files:
        return None
    att = pd.concat([pd.read_parquet(p) for p in files], ignore_index=True)
    sources.update({f"attribution/{p.name}": sha(p) for p in files})
    sources["freeze manifest"] = sha(Path(freeze))
    preds = pd.concat([pd.read_parquet(p, columns=["run_id", "split", "window_id", "render_id", "pred_class"])
                       for p in ev.files_from_freeze(freeze)], ignore_index=True)
    preds = preds[(preds["split"] == "test") & preds["run_id"].isin(set(att["run_id"]))]
    return attribution_flip_auroc(att, preds)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eval-dir", default="outputs/eval")
    ap.add_argument("--out", default="report/generated")
    ap.add_argument("--masking-dir")
    ap.add_argument("--attribution-dir")
    ap.add_argument("--freeze", help="results-freeze manifest (test predictions for the attribution-to-flip link)")
    ap.add_argument("--data-root", help="render_v1 root, for Figure 1")
    ap.add_argument("--allow-synthetic", action="store_true", help="preview from synthetic outputs, outside report/")
    a = ap.parse_args(argv)
    try:
        man = generate(a.eval_dir, a.out, a.masking_dir, a.attribution_dir, a.freeze, a.data_root, a.allow_synthetic)
    except AssetRefused as exc:
        print(f"REFUSED: {exc}")
        return 2
    print(f"wrote {len(man['written'])} assets to {a.out}" + (" (SYNTHETIC preview)" if man["synthetic"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())

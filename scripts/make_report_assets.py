def masking_frames(masking_dir):
    from src.interpretability.link import masking_summary
    files = sorted(Path(masking_dir).glob("*.parquet"))
    if not files:
        return None, {}
    df = pd.concat([pd.read_parquet(p) for p in files], ignore_index=True)
    exp_of = {}
    for p in files:
        meta = p.with_suffix(".json")
        rid = pd.read_parquet(p, columns=["run_id"])["run_id"].iloc[0]
        exp_of[rid] = json.loads(meta.read_text())["experiment_id"] if meta.exists() else rid.split("_s")[0]
    s = masking_summary(df)
    s["experiment_id"] = s["run_id"].map(exp_of)
    return s, {f"masking/{p.name}": sha(p) for p in files}



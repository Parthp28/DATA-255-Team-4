def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def fmt(x, nd=3) -> str:
    return "--" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"{x:.{nd}f}"


def pm(mean, sd, nd=3) -> str:
    if mean is None or not math.isfinite(mean):
        return "--"
    return fmt(mean, nd) if sd is None or not math.isfinite(sd) else f"{fmt(mean, nd)} $\\pm$ {fmt(sd, nd)}"


class Writer:
    def __init__(self, out: Path, sources: dict, synthetic: bool):
        self.out, self.sources, self.synthetic = out, sources, synthetic
        self.written = []
        (out / "tables").mkdir(parents=True, exist_ok=True)
        (out / "figures").mkdir(parents=True, exist_ok=True)

    def header(self, used) -> str:
        lines = ["% Generated by scripts/make_report_assets.py. Do not edit; rerun the generator."]
        lines += [f"% source {k}: sha256 {self.sources[k]}" for k in used if k in self.sources]
        if self.synthetic:
            lines.append(f"% {STAMP}")
        return "\n".join(lines) + "\n"

    def table(self, name, used, caption, label, colspec, head, rows, wide=False, note=""):
        env = "table*" if wide else "table"
        cap = (f"\\textcolor{{red}}{{[{STAMP}]}} " if self.synthetic else "") + caption
        body = [self.header(used), f"\\begin{{{env}}}[t]", "\\centering", "\\footnotesize",
                f"\\caption{{{cap}}}", f"\\label{{{label}}}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule",
                " & ".join(head) + " \\\\", "\\midrule"]
        body += [" & ".join(r) + " \\\\" for r in rows]
        body += ["\\bottomrule", "\\end{tabular}"]
        if note:
            body.append(f"\\par\\smallskip\\parbox{{0.95\\linewidth}}{{\\scriptsize {note}}}")
        body.append(f"\\end{{{env}}}")
        p = self.out / "tables" / name
        p.write_text("\n".join(body) + "\n", encoding="utf-8")
        self.written.append(str(p.relative_to(self.out)).replace("\\", "/"))

    def figure(self, name, fig):
        if self.synthetic:
            fig.text(0.5, 0.5, STAMP, ha="center", va="center", rotation=20, fontsize=22, color="#d03b3b",
                     alpha=0.35, weight="bold")
        p = self.out / "figures" / name
        fig.savefig(p, bbox_inches="tight", transparent=True)
        plt.close(fig)
        self.written.append(str(p.relative_to(self.out)).replace("\\", "/"))


def style_axes(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(AXIS)
    ax.tick_params(colors=INK2, labelsize=8, length=0)
    ax.yaxis.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def seeds_value(seeds, exp, metric):
    r = seeds[(seeds["experiment_id"] == exp) & (seeds["metric"] == metric)]
    return (float(r["mean"].iloc[0]), float(r["sd"].iloc[0])) if len(r) else (None, None)


def present(exps, have):
    return [e for e in EXP_ORDER if e in have and e in exps]



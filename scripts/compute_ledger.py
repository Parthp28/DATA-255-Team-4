"""Compute ledger for the Sustainability section (plan 13, Appendix A row 2). Owner: Kaushik.

    python scripts/compute_ledger.py --runs-dir outputs/runs --out outputs/eval/compute_ledger.csv \
        --tex report/generated/tables/table_ledger.tex

Reads every outputs/runs/*/run.json and totals the measured compute per experiment and run category:

    GPU-hours  = gpu_minutes / 60 from each run record (runtime-measured, never estimated)
    energy kWh = GPU-hours x board power of the recorded GPU model (RTX 5090: 575 W; T4: 70 W) -- an upper bound,
                 since a GPU rarely draws its full board power

Categories: final (trained with a frozen configuration), tuning/dev (everything else that completed), debug
(--max-steps), superseded, and failed. CPU runs (E5, B0) count wall-clock hours and no GPU energy; CPU energy is not
measured, and the table says so. The ledger groups only by experiment, category and GPU model. Compute logistics
(executors, lanes, queue ids) are never read or written (plan 10.8 firewall).
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import pandas as pd

BOARD_POWER_W = {"RTX 5090": 575.0, "T4": 70.0}   # NVIDIA board power (total graphics power); D16 GPU first
LEDGER_COLUMNS = ["experiment_id", "category", "gpu_model", "runs", "gpu_hours", "wall_hours", "energy_kwh"]
SAFE_FIELDS = ("run_id", "experiment_id", "status", "max_steps", "frozen_config_path", "gpu_model", "gpu_minutes",
               "wall_minutes", "data_version")


def category(rec: dict) -> str:
    if rec.get("status") == "superseded" or rec.get("validation_status") == "superseded":
        return "superseded"
    if rec.get("status") not in ("complete", "promoted"):
        return "failed"
    if rec.get("max_steps"):
        return "debug"
    return "final" if rec.get("frozen_config_path") else "tuning/dev"


def power_w(gpu_model: str):
    if not gpu_model or gpu_model == "cpu":
        return 0.0
    for key, w in BOARD_POWER_W.items():
        if key in gpu_model:
            return w
    return float("nan")                  # unknown GPU: energy not claimed


def load_records(runs_dir) -> pd.DataFrame:
    rows = []
    for p in sorted(Path(runs_dir).glob("*/run.json")):
        rec = json.loads(p.read_text())
        r = {k: rec.get(k) for k in SAFE_FIELDS}
        r["validation_status"] = rec.get("validation_status")
        r["category"] = category(rec)
        rows.append(r)
    return pd.DataFrame(rows, columns=list(SAFE_FIELDS) + ["validation_status", "category"])


def ledger(records: pd.DataFrame) -> pd.DataFrame:
    if records.empty:
        return pd.DataFrame(columns=LEDGER_COLUMNS)
    r = records.assign(gpu_model=records["gpu_model"].fillna("unknown"),
                       gpu_hours=pd.to_numeric(records["gpu_minutes"], errors="coerce").fillna(0.0) / 60.0,
                       wall_hours=pd.to_numeric(records["wall_minutes"], errors="coerce").fillna(0.0) / 60.0)
    r["energy_kwh"] = [h * power_w(g) / 1000.0 for h, g in zip(r["gpu_hours"], r["gpu_model"])]
    out = (r.groupby(["experiment_id", "category", "gpu_model"], dropna=False)
           .agg(runs=("run_id", "size"), gpu_hours=("gpu_hours", "sum"), wall_hours=("wall_hours", "sum"),
                energy_kwh=("energy_kwh", lambda s: s.sum(min_count=1) if s.notna().all() else float("nan")))
           .reset_index())
    total = pd.DataFrame([{"experiment_id": "TOTAL", "category": "all", "gpu_model": "all", "runs": int(out["runs"].sum()),
                           "gpu_hours": out["gpu_hours"].sum(), "wall_hours": out["wall_hours"].sum(),
                           "energy_kwh": out["energy_kwh"].sum(min_count=1) if out["energy_kwh"].notna().all()
                           else float("nan")}])
    return pd.concat([out, total], ignore_index=True)[LEDGER_COLUMNS]


def to_latex(led: pd.DataFrame, source_sha: str = "") -> str:
    def f(x, nd=2):
        return "--" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"{x:.{nd}f}"
    lines = ["% Generated by scripts/compute_ledger.py. Do not edit; rerun the script.",
             f"% source run records: sha256 {source_sha}" if source_sha else "% source run records",
             "\\begin{table}[t]", "\\centering", "\\footnotesize",
             "\\caption{Compute ledger from the run records.}", "\\label{tab:ledger}",
             "\\begin{tabular}{lllrrrr}", "\\toprule",
             "Exp. & Category & Device & Runs & GPU-h & Wall-h & kWh \\\\", "\\midrule"]
    for r in led.itertuples(index=False):
        dev = "CPU" if r.gpu_model == "cpu" else r.gpu_model.replace("_", "\\_")
        if r.experiment_id == "TOTAL":
            lines.append("\\midrule")
        lines.append(f"{r.experiment_id} & {r.category} & {dev} & {r.runs} & {f(r.gpu_hours)} & {f(r.wall_hours)} & "
                     f"{f(r.energy_kwh, 3)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\par\\smallskip\\parbox{0.95\\linewidth}{\\scriptsize kWh = GPU-hours $\\times$ the board power of the recorded GPU (NVIDIA GeForce RTX 5090: 575 W), an upper bound; "
              "board power. CPU runs (E5, B0) add wall-clock time only; CPU energy was not measured. -- = GPU model "
              "without a recorded board power.}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def records_sha(runs_dir) -> str:
    import hashlib
    h = hashlib.sha256()
    for p in sorted(Path(runs_dir).glob("*/run.json")):
        h.update(p.parent.name.encode() + b"\0" + p.read_bytes())
    return h.hexdigest()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--runs-dir", default="outputs/runs")
    ap.add_argument("--out", default="outputs/eval/compute_ledger.csv")
    ap.add_argument("--tex", help="also write the LaTeX table (report/generated/tables/table_ledger.tex)")
    a = ap.parse_args(argv)
    recs = load_records(a.runs_dir)
    if recs["data_version"].astype(str).str.startswith("synthetic").any() and a.tex and "report" in Path(a.tex).parts:
        print("REFUSED: synthetic run records may not feed the report's ledger")
        return 2
    led = ledger(recs)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    led.to_csv(a.out, index=False)
    if a.tex:
        Path(a.tex).parent.mkdir(parents=True, exist_ok=True)
        Path(a.tex).write_text(to_latex(led, records_sha(a.runs_dir)), encoding="utf-8")
    tot = led[led["experiment_id"] == "TOTAL"]
    if len(tot):
        t = tot.iloc[0]
        print(f"{int(t['runs'])} runs | {t['gpu_hours']:.2f} GPU-h | {t['wall_hours']:.2f} wall-h | "
              f"{t['energy_kwh']:.3f} kWh -> {a.out}")
    else:
        print(f"no run records in {a.runs_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
